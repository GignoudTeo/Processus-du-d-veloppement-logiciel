-- ========================================================
-- MIGRATION SPRINT 5 : inscriptions validées par le coach, liste d'attente,
-- historique des refus / désinscriptions / annulations, passages en salle,
-- progression, incidents et rappels.
--
-- À coller en entier dans Supabase (SQL Editor) puis "Run", en une seule fois.
-- Les données existantes sont conservées. Le script peut être relancé sans erreur
-- ni doublon (il ne refait que ce qui manque).
-- ========================================================

BEGIN;

-- ========================================================
-- 1. Nouveau statut de réservation 'en_attente'
-- ========================================================
-- 'en_attente' : demande d'inscription en attente de validation par le coach.
-- Autres statuts : 'confirmee' (validée), 'liste_attente', 'rejetee' (refusée),
-- 'absent' (désinscrit), 'annulee' (a quitté la liste d'attente).
--
-- PostgreSQL n'accepte pas d'utiliser une valeur ajoutée à un ENUM dans la même
-- transaction (ALTER TYPE ... ADD VALUE). On recrée donc le type avec la nouvelle
-- valeur et on y convertit la colonne : tout se fait en une seule exécution.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_enum e
        JOIN pg_type t ON t.oid = e.enumtypid
        WHERE t.typname = 'statut_reservation' AND e.enumlabel = 'en_attente'
    ) THEN
        CREATE TYPE statut_reservation_nouveau AS ENUM (
            'en_attente', 'confirmee', 'annulee', 'liste_attente', 'rejetee', 'absent'
        );

        ALTER TABLE reservations ALTER COLUMN statut DROP DEFAULT;
        ALTER TABLE reservations
            ALTER COLUMN statut TYPE statut_reservation_nouveau
            USING statut::text::statut_reservation_nouveau;

        DROP TYPE statut_reservation;
        ALTER TYPE statut_reservation_nouveau RENAME TO statut_reservation;
    END IF;
END $$;

-- Toute nouvelle inscription commence en attente de validation
ALTER TABLE reservations ALTER COLUMN statut SET DEFAULT 'en_attente';

-- ========================================================
-- 2. Nouvelles colonnes
-- ========================================================

-- Motif et date du dernier changement de statut (refus, désinscription...)
ALTER TABLE reservations
    ADD COLUMN IF NOT EXISTS motif TEXT DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS date_statut TIMESTAMPTZ DEFAULT NULL;

-- Rappel J-3 au coach : envoyé une seule fois par séance
ALTER TABLE cours
    ADD COLUMN IF NOT EXISTS rappel_envoye_le TIMESTAMPTZ DEFAULT NULL;

-- Description d'une séance (déjà présente dans certaines bases)
ALTER TABLE cours
    ADD COLUMN IF NOT EXISTS description TEXT DEFAULT NULL;

-- ========================================================
-- 3. Nouvelles tables
-- ========================================================

-- Refus, désinscriptions et annulations de séance.
-- Les noms sont recopiés : l'historique reste lisible même si la séance,
-- le coach ou l'adhérent est supprimé ensuite (pas de clé étrangère sur id_cours).
CREATE TABLE IF NOT EXISTS historique_seances (
    id_evenement INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL
        CHECK (type IN ('refus', 'desinscription', 'annulation')),
    date_evenement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motif TEXT NOT NULL,

    id_cours INTEGER NOT NULL,
    titre_cours VARCHAR(150) NOT NULL,
    date_cours TIMESTAMPTZ NOT NULL,
    nom_salle VARCHAR(100) DEFAULT NULL,

    id_coach INTEGER DEFAULT NULL
        REFERENCES coachs(id_coach)
        ON DELETE SET NULL ON UPDATE CASCADE,
    nom_coach VARCHAR(201) DEFAULT NULL,

    -- NULL pour la ligne "séance annulée" vue côté coach
    id_adherent INTEGER DEFAULT NULL
        REFERENCES adherents(id_adherent)
        ON DELETE SET NULL ON UPDATE CASCADE,
    nom_adherent VARCHAR(201) DEFAULT NULL
);

CREATE INDEX IF NOT EXISTS idx_historique_type_date ON historique_seances(type, date_evenement);
CREATE INDEX IF NOT EXISTS idx_historique_coach ON historique_seances(id_coach);
CREATE INDEX IF NOT EXISTS idx_historique_adherent ON historique_seances(id_adherent);

-- Entrées et sorties de la salle (saisies à la main, pas de lecteur de badge)
CREATE TABLE IF NOT EXISTS passages (
    id_passage INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_adherent INTEGER NOT NULL
        REFERENCES adherents(id_adherent)
        ON DELETE CASCADE ON UPDATE CASCADE,
    entree TIMESTAMPTZ NOT NULL,
    -- NULL : passage incomplet (sortie non enregistrée)
    sortie TIMESTAMPTZ DEFAULT NULL,
    CONSTRAINT chk_passages_sortie CHECK (sortie IS NULL OR sortie > entree)
);

CREATE INDEX IF NOT EXISTS idx_passages_adherent_entree ON passages(id_adherent, entree);

-- Mesures saisies par l'adhérent. L'IMC est calculé par le site, il n'est pas stocké.
CREATE TABLE IF NOT EXISTS progression (
    id_mesure INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_adherent INTEGER NOT NULL
        REFERENCES adherents(id_adherent)
        ON DELETE CASCADE ON UPDATE CASCADE,
    date_mesure DATE NOT NULL,
    poids DECIMAL(5,2) NOT NULL CHECK (poids BETWEEN 20 AND 300),
    taille DECIMAL(5,2) NOT NULL CHECK (taille BETWEEN 100 AND 250),
    duree_seance SMALLINT NOT NULL CHECK (duree_seance BETWEEN 1 AND 600)
);

CREATE INDEX IF NOT EXISTS idx_progression_adherent_date ON progression(id_adherent, date_mesure);

-- Incidents signalés par un coach sur une de ses séances
CREATE TABLE IF NOT EXISTS incidents (
    id_incident INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_coach INTEGER NOT NULL
        REFERENCES coachs(id_coach)
        ON DELETE CASCADE ON UPDATE CASCADE,
    id_cours INTEGER NOT NULL,
    titre_cours VARCHAR(150) NOT NULL,
    date_cours TIMESTAMPTZ NOT NULL,
    date_signalement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    description TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_incidents_coach ON incidents(id_coach);


-- ========================================================
-- 4. JEU DE DONNÉES : passages en salle
-- ========================================================
-- Les 5 premiers adhérents, sur les 6 dernières semaines : 3 venues par semaine
-- (lundi, mercredi, samedi), de 45 min à 1 h 45. Quelques passages sans sortie
-- pour tester l'affichage "incomplet".
-- Seulement si la table est encore vide : relancer le script ne crée pas de doublons.

INSERT INTO passages (id_adherent, entree, sortie)
SELECT
    a.id_adherent,
    jour + (TIME '17:00' + (a.rang * 30) * INTERVAL '1 minute'),
    CASE
        WHEN (a.rang + semaine) % 4 = 0 AND extract(isodow FROM jour) = 6 THEN NULL
        ELSE jour + (TIME '17:00' + (a.rang * 30) * INTERVAL '1 minute')
                  + ((45 + ((a.rang * 15 + semaine * 10) % 60)) * INTERVAL '1 minute')
    END
FROM (
    SELECT id_adherent, ROW_NUMBER() OVER (ORDER BY id_adherent) - 1 AS rang
    FROM adherents
    ORDER BY id_adherent
    LIMIT 5
) a
CROSS JOIN generate_series(1, 6) AS semaine
CROSS JOIN LATERAL (
    SELECT (date_trunc('week', CURRENT_DATE) - (semaine * INTERVAL '1 week') + d * INTERVAL '1 day')::date AS jour
    FROM unnest(ARRAY[0, 2, 5]) AS d
) jours
WHERE NOT EXISTS (SELECT 1 FROM passages);

COMMIT;
